"""Independent scientific audit of real-data outputs from figure_08_wdbc_baselines.py.
No synthetic data; malignant-positive scores are 1-P(benign) on the authentic WDBC test split.
"""
from pathlib import Path
import csv, json, hashlib
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from sklearn.metrics import roc_curve, roc_auc_score, confusion_matrix, accuracy_score, precision_recall_curve, average_precision_score
from sklearn.calibration import calibration_curve
ROOT=Path(__file__).resolve().parent
FIG=ROOT/'outputs'
with (FIG/'heldout_predictions.csv').open() as f:rows=list(csv.DictReader(f))
s = [r for r in rows if r['model']=='Logistic regression']
y=1-np.asarray([int(r['true_label']) for r in s])
p=1-np.asarray([float(r['probability_benign']) for r in s])
assert len(p)==114 and y.sum()==42 and len(rows)==456
fpr,tpr,_=roc_curve(y,p)
pre,rec,_=precision_recall_curve(y,p)
cm=confusion_matrix(y,p>=.5,labels=[0,1]);auc=roc_auc_score(y,p);ap=average_precision_score(y,p)
# Stratified case bootstrap intervals reflect only the fixed internal test cohort.
rng=np.random.default_rng(20261118)
positive=np.where(y==1)[0];negative=np.where(y==0)[0]
auc_boot=[];sens_boot=[];spec_boot=[]
for i in range(2000):
    idx=np.r_[rng.choice(positive,len(positive),replace=True),rng.choice(negative,len(negative),replace=True)]
    auc_boot.append(roc_auc_score(y[idx],p[idx]))
    pred=(p[idx]>=.5)
    sens_boot.append(float(np.mean(pred[y[idx]==1])))
    spec_boot.append(float(np.mean(~pred[y[idx]==0])))

def ci(v):return [round(float(x),5) for x in np.percentile(v,[2.5,97.5])]

fig,ax=plt.subplots(1,3,figsize=(13.5,3.8),layout='constrained')
blue='#21465e'; teal='#287d79'; gold='#b58845'
ax[0].plot(fpr,tpr,color=teal,lw=2.1,label=f'ROC AUC {auc:.4f}')
ax[0].plot([0,1],[0,1],':',c='#929da4',lw=1)
ax[0].set(xlabel='False-positive rate (benign cases)',ylabel='Sensitivity (malignant cases)',title='(a) Held-out malignant detection',xlim=(0,1),ylim=(0,1.02))
ax[0].legend(frameon=False,loc='lower right',fontsize=8)
ax[1].plot(rec,pre,color=blue,lw=2.1,label=f'Average precision {ap:.4f}')
ax[1].axhline(y.mean(),color=gold,linestyle='--',label=f'Malignant prevalence {y.mean():.3f}')
ax[1].set(xlabel='Recall (malignant cases)',ylabel='Precision (malignant cases)',title='(b) Precision–recall on test cases',xlim=(0,1),ylim=(0,1.02))
ax[1].legend(frameon=False,fontsize=8,loc='lower left')
# Actual test score distributions; deterministic horizontal jitter for visibility only, not measurements
rng2=np.random.default_rng(15)
for group,color,label in [(0,gold,'Benign'),(1,teal,'Malignant')]:
    idx=y==group
    ax[2].scatter(p[idx],np.full(idx.sum(),group)+rng2.uniform(-.13,.13,idx.sum()),s=22,alpha=.72,color=color,edgecolor='white',linewidth=.2,label=f'{label} (n={idx.sum()})')
ax[2].axvline(.5,color='#60686e',lw=1,linestyle='--')
ax[2].set(xlabel='Model-predicted malignancy probability',ylabel='Actual diagnosis',title='(c) Individual test scores',yticks=[0,1],yticklabels=['Benign','Malignant'],ylim=(-.4,1.4),xlim=(-.02,1.02))
ax[2].legend(frameon=False,fontsize=8,loc='center left')
for a in ax:a.grid(alpha=.16)
fig.savefig(FIG/'WDBC_malignant_positive_scientific_audit.png',dpi=230,facecolor='white')
fig.savefig(FIG/'WDBC_malignant_positive_scientific_audit.pdf',facecolor='white')
fig.savefig(FIG/'WDBC_malignant_positive_scientific_audit.svg',facecolor='white')
plt.close(fig)
record={'source':'Authentic WDBC held-out test predictions generated by existing AppliedML GitHub code/figure_08_wdbc_baselines.py',
        'positive_class':'malignant (inverted from original sklearn positive benign coding)',
        'train_n':455,'test_n':114,'malignant_test_n':int(y.sum()),'benign_test_n':int((1-y).sum()),
        'auc':float(auc),'auc_stratified_bootstrap_95CI':ci(auc_boot),
        'average_precision':float(ap),'sensitivity':float(cm[1,1]/cm[1].sum()),
        'sensitivity_CI':ci(sens_boot), 'specificity':float(cm[0,0]/cm[0].sum()),
        'specificity_CI':ci(spec_boot),'accuracy':float(accuracy_score(y,p>=.5)),
        'confusion_true_benign_malignant':cm.tolist(),
        'limitations':'Internal retrospective test only; 2000 case bootstraps do not capture site shift, independent clinical deployment, model-selection variability or patient-level external validation.'}
(FIG/'malignant_positive_metrics.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps(record,indent=2))
