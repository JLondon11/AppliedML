"""Publication-grade Scientific AI Figures 2–3, from real observations and saved predictions.

Usage:
python chapters/scientific_ai/code/render_verified_figures_02_03.py \
  --evidence /path/to/scientific_ai_fig02_real/outputs \
  --output chapters/scientific_ai/figures

Never uses hand-entered performance numbers, synthetic observations or invented model outputs.
Requires numpy, matplotlib, scikit-learn, statsmodels. Source JSON must have been
generated by the committed figure_02 and figure_03 experimental scripts.
"""
import argparse, json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.datasets import load_breast_cancer
from sklearn.model_selection import train_test_split
from sklearn.metrics import confusion_matrix, roc_auc_score
from statsmodels.datasets import sunspots

NAVY="#193A54"; DARK="#263646"; TEAL="#2D786D"; COPPER="#B66B40"
LIGHT="#8EA2AD"; GRID="#E7EDF0"
plt.rcParams.update({
    "font.family":"DejaVu Sans","font.size":10.5,"axes.titlesize":12,
    "axes.titleweight":"semibold","axes.labelsize":10,
    "axes.spines.top":False,"axes.spines.right":False,
    "axes.edgecolor":"#798B98","xtick.color":DARK,"ytick.color":DARK,
    "text.color":DARK,"axes.labelcolor":DARK,
    "figure.facecolor":"white","axes.facecolor":"white","savefig.facecolor":"white"
})
def polish(ax):
    ax.grid(color=GRID,lw=.7,zorder=0)
    ax.set_axisbelow(True)
def save(fig,out,stem):
    for ext in ("png","pdf","svg"):
        fig.savefig(out/(stem+"."+ext),dpi=250,bbox_inches="tight")
    plt.close(fig)

def solar(evidence,out):
    record=json.loads((evidence/"figure_02_scientific_discovery_evidence.json").read_text())
    d=sunspots.load_pandas().data
    values=d.SUNACTIVITY.to_numpy()
    years=d.YEAR.to_numpy().astype(int)
    assert len(values)==309 and np.allclose(values[years>=1950],record["observed_test"])
    t=np.asarray(record["test_target_years"])
    y=np.asarray(record["observed_test"])
    pred=np.asarray(record["ridge_predictions_test"])
    base=np.asarray(record["persistence_predictions_test"])
    assert len(y)==59
    model_rmse=float(np.sqrt(np.mean((y-pred)**2)))
    baseline_rmse=float(np.sqrt(np.mean((y-base)**2)))
    assert np.isclose(model_rmse,record["heldout_rmse"],rtol=1e-12)
    assert np.isclose(baseline_rmse,record["persistence_heldout_rmse"],rtol=1e-12)
    fig=plt.figure(figsize=(12,8.25),layout="constrained")
    gs=fig.add_gridspec(2,2,height_ratios=[1.02,1],hspace=.09,wspace=.1)
    top=fig.add_subplot(gs[0,:]);left=fig.add_subplot(gs[1,0]);right=fig.add_subplot(gs[1,1])
    top.plot(years,values,c=LIGHT,lw=.95,label="Observed annual activity")
    rolling=np.convolve(values,np.ones(11)/11,mode="valid")
    top.plot(years[5:-5],rolling,c=COPPER,lw=2,label="Centered 11-year mean")
    top.axvspan(1950,2008,color=TEAL,alpha=.085,lw=0)
    top.set(title="(a) Recorded solar activity and longer-period variation",
            ylabel="Annual sunspot number",xlabel="Year",xlim=(1700,2008))
    polish(top);top.legend(loc="upper left",frameon=False,ncol=2,fontsize=9)
    left.scatter(values[:-1],values[1:],s=16,c=TEAL,alpha=.62,linewidths=0,rasterized=True)
    left.plot([0,200],[0,200],ls="--",lw=1,c=LIGHT)
    left.set(title="(b) Measured year-to-year dependence",
             xlabel="Sunspot number at year t − 1",ylabel="Sunspot number at year t",
             xlim=(0,200),ylim=(0,200))
    polish(left);left.set_aspect("equal",adjustable="box")
    right.plot(t,y,c=NAVY,lw=2.1,label="Observed")
    right.plot(t,pred,c=COPPER,lw=1.6,label=f"Ridge model · RMSE {model_rmse:.2f}")
    right.plot(t,base,c=TEAL,lw=1,alpha=.55,label=f"Persistence · RMSE {baseline_rmse:.2f}")
    right.set(title="(c) Held-out one-year forecast, 1950–2008",
              xlabel="Target year",ylabel="Annual sunspot number",xlim=(1950,2008))
    polish(right);right.legend(loc="upper center",bbox_to_anchor=(.5,-.24),
                               frameon=False,ncol=1,fontsize=9)
    fig.suptitle("Scientific inference from authentic annual sunspot observations",
                 fontsize=16,fontweight="bold",color=NAVY)
    save(fig,out,"figure_02_evolution_scientific_discovery")
    return {"original_observations":309,"test_targets":59,
            "ridge_rmse":model_rmse,"persistence_rmse":baseline_rmse}

def biomedical(evidence,out):
    record=json.loads((evidence/"figure_03_scientific_ai_real_data_evidence.json").read_text())
    data=load_breast_cancer()
    X=data.data
    labels=(data.target==0).astype(int)
    inds=np.arange(len(labels))
    trainval,test=train_test_split(inds,test_size=114,stratify=labels,random_state=20261109)
    train,val=train_test_split(trainval,test_size=114,stratify=labels[trainval],random_state=20261110)
    assert (len(train),len(val),len(test))==(341,114,114)
    assert np.array_equal(labels[test],record["test_labels"])
    p=np.asarray(record["test_probabilities_malignant"])
    pred=np.asarray(record["test_predicted_labels"])
    truth=np.asarray(record["test_labels"])
    cm=confusion_matrix(truth,pred,labels=[0,1])
    assert np.array_equal(cm,record["test_confusion_matrix_true_benign_malignant"])
    auc=float(roc_auc_score(truth,p))
    assert np.isclose(auc,record["test_roc_auc"],rtol=1e-12)
    fig=plt.figure(figsize=(12.6,8.25),layout="constrained")
    gs=fig.add_gridspec(2,2,height_ratios=[1,1],hspace=.06,wspace=.08)
    a=fig.add_subplot(gs[0,0]);b=fig.add_subplot(gs[0,1])
    c=fig.add_subplot(gs[1,0]);d=fig.add_subplot(gs[1,1])
    for label,col,name in ((0,TEAL,"Benign"),(1,COPPER,"Malignant")):
        subset=labels[train]==label
        a.scatter(X[train,0][subset],X[train,1][subset],
                  s=22,c=col,alpha=.62,linewidths=0,
                  label=f"{name} (n={int(subset.sum())})",rasterized=True)
    a.set(title="(a) Measured cell-nucleus characteristics",
          xlabel="Mean radius (dataset units)",ylabel="Mean texture")
    polish(a);a.legend(loc="upper right",frameon=False,fontsize=9)
    columns=[0,1,2,3,4,5]
    names=["Radius","Texture","Perimeter","Area","Smoothness","Compactness"]
    corr=np.corrcoef(X[train][:,columns],rowvar=False)
    heat=b.imshow(corr,cmap="RdBu_r",vmin=-1,vmax=1)
    b.set(title="(b) Training-set feature correlations",
          xticks=range(6),yticks=range(6))
    b.set_xticklabels(names,rotation=35,ha="right",fontsize=9)
    b.set_yticklabels(names,fontsize=9)
    for i in range(6):
        for j in range(6):
            if i!=j and abs(corr[i,j])>.58:
                b.text(j,i,f"{corr[i,j]:.2f}",ha="center",va="center",
                       fontsize=7,color="white" if abs(corr[i,j])>.65 else DARK)
    fig.colorbar(heat,ax=b,fraction=.046,pad=.03,label="Pearson r")
    bins=np.linspace(0,1,21)
    for label,col,name in ((0,TEAL,"Benign"),(1,COPPER,"Malignant")):
        mask=truth==label
        c.hist(p[mask],bins=bins,color=col,alpha=.76,
               label=f"{name} (n={int(mask.sum())})",edgecolor="white",lw=.4)
    c.set(title="(c) Held-out prediction probabilities",
          xlabel="Probability of malignant disease",ylabel="Case count",xlim=(0,1))
    polish(c);c.legend(loc="upper center",frameon=False,fontsize=9)
    d.imshow(cm,cmap="Blues",vmin=0,vmax=max(80,int(cm.max()+4)))
    for (i,j),value in np.ndenumerate(cm):
        d.text(j,i,str(value),ha="center",va="center",fontsize=19,
               fontweight="bold",color="white" if value>34 else DARK)
    d.set(title=f"(d) Held-out classification · AUC {auc:.4f}",
          xlabel="Predicted class",ylabel="Recorded diagnosis",xticks=[0,1],yticks=[0,1])
    d.set_xticklabels(["Benign","Malignant"])
    d.set_yticklabels(["Benign","Malignant"])
    fig.suptitle("Observed biomedical features and verified model predictions",
                 fontsize=16,fontweight="bold",color=NAVY)
    save(fig,out,"figure_03_evolution_scientific_ai")
    return {"original_cases":569,"train":341,"validation":114,
            "test":114,"heldout_auc":auc,"confusion_matrix":cm.tolist()}

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--evidence",type=Path,required=True)
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    info={"figure_02":solar(args.evidence,args.output),
          "figure_03":biomedical(args.evidence,args.output)}
    (args.output/"quality_verification.json").write_text(json.dumps(info,indent=2)+"\n")
    print(json.dumps(info,indent=2))

if __name__=="__main__":
    main()
