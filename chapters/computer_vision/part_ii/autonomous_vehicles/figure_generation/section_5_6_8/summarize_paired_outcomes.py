"""Paired bootstrap interval for synthetic planning outcome difference.
Reads train_track_plan_episodes.csv generated by execute_train_track_plan.py.
Seed 9921; reports paired 95% percentile interval, not a clinical or road result.
"""
from pathlib import Path
import csv
import numpy as np
ROOT=Path(__file__).resolve().parent
with (ROOT/'train_track_plan_episodes.csv').open() as f:
    rows=list(csv.DictReader(f))
a=np.array([int(r['reactive_collision']) for r in rows])
b=np.array([int(r['predictive_collision']) for r in rows])
rng=np.random.default_rng(9921)
idx=rng.integers(0,len(rows),size=(10000,len(rows)))
lo,hi=np.percentile((a[idx]-b[idx]).mean(axis=1),[2.5,97.5])
print('reactive_minus_predictive',a.mean()-b.mean())
print('paired_bootstrap_95percent_interval',lo,hi)
print('discordant_pairs_reactive_only',int(np.sum((a==1)&(b==0))))
print('discordant_pairs_predictive_only',int(np.sum((a==0)&(b==1))))
